from pydantic import BaseModel, Field
from typing import List, Optional

# Existing Pydantic schemas (unchanged)
class DocumentUploadResponse(BaseModel):
    document_id: int = Field(..., description="Database ID of the stored document")
    filename: str = Field(..., description="Original uploaded filename")
    document_type: str = Field(..., description="Inferred document type")
    uploaded_at: str = Field(..., description="Timestamp of upload (ISO 8601)")
    status: str = Field(..., description="Processing status, e.g., 'processed'")

class KnowledgeQueryRequest(BaseModel):
    question: str = Field(..., description="User question to answer using RAG")
    filters: Optional[dict] = Field(None, description="Optional filters, e.g., {'document_type': 'BANK_POLICY'}")
    top_k: Optional[int] = Field(None, description="Number of chunks to retrieve; defaults to config VECTOR_TOP_K")

class SourceInfo(BaseModel):
    document_id: int
    document_name: str
    chunk_id: int
    page: Optional[int] = None
    metadata: Optional[dict] = None

class KnowledgeQueryResponse(BaseModel):
    answer: str = Field(..., description="Grounded answer generated by LLM")
    sources: List[SourceInfo] = Field(..., description="List of evidential sources used for the answer")

