from sqlalchemy import Column, Integer, String, DateTime, Text, JSON, ForeignKey, UniqueConstraint
from sqlalchemy.orm import relationship
from sqlalchemy.sql import func
from backend.app.db import Base
# Removed circular import of Business to avoid circular dependency

class Document(Base):
    __tablename__ = "documents"
    __table_args__ = (
        UniqueConstraint('business_id', 'content_hash', name='uq_documents_business_hash'),
    )
    id = Column(Integer, primary_key=True, index=True)
    business_id = Column(Integer, ForeignKey('businesses.id', ondelete='CASCADE'), nullable=False, index=True)
    filename = Column(String, nullable=False)
    document_type = Column(String, nullable=False)
    source = Column(String, nullable=True)
    uploaded_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)
    content_hash = Column(String, nullable=False)
    status = Column(String, nullable=False, server_default='pending')
    failure_reason = Column(String, nullable=True)

    business = relationship('Business', back_populates='documents')
    document_chunks = relationship('DocumentChunk', back_populates='document', cascade='all, delete-orphan')

class DocumentChunk(Base):
    __tablename__ = "document_chunks"
    __table_args__ = (
        UniqueConstraint('document_id', 'chunk_number', name='uq_document_chunk_number'),
    )
    id = Column(Integer, primary_key=True, index=True)
    document_id = Column(Integer, ForeignKey('documents.id', ondelete='CASCADE'), nullable=False, index=True)
    chunk_number = Column(Integer, nullable=False)
    text = Column(Text, nullable=False)
    # Store embedding as JSON for proper list serialization
    # Use JSON column for embeddings across all databases for compatibility in tests
    embedding_type = JSON
    embedding = Column(embedding_type, nullable=True)
    # Preserve original column name 'metadata' via explicit name mapping
    metadata_json = Column('metadata', JSON, nullable=True)
    
    def __init__(self, **kwargs):
        # Accept both 'metadata' and 'meta' as aliases for the JSON metadata column
        metadata = kwargs.pop('metadata', None)
        # 'meta' is the name used in tests; treat it as metadata if provided
        if metadata is None:
            metadata = kwargs.pop('meta', None)
        super().__init__(**kwargs)
        if metadata is not None:
            self.metadata_json = metadata

    document = relationship('Document', back_populates='document_chunks')
